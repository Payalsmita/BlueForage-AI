package com.blueprintforge;

import com.blueprintforge.Models.*;

import java.util.*;

/**
 * MOCK iCIMS-style configuration built from the approved blueprint. Not an official iCIMS schema: it shows how a
 * blueprint could map onto workflow statuses, user roles and approval chains, with traceability back to evidence.
 */
final class IcimsExport {
    private IcimsExport() {}

    static final String NOTICE = "MOCK configuration in an iCIMS-like shape, generated by BlueprintForge AI from approved "
            + "blueprint items. Not an official iCIMS schema; a consultant must review it before any real configuration.";

    // ponytail: keyword heuristics; replace with a real status-to-bin mapping table once one exists
    static String bin(String stage) {
        String s = stage.toLowerCase();
        if (s.contains("offer")) return "OFFER";
        if (s.matches(".*(committee|decision).*")) return "SELECTION";
        if (s.matches(".*(background|drug|medical|physical|health|licen[cs]e|registration|fingerprint|reference|dbs|i-9"
                + "|verification|credit|criminal|clearance|pria|visa|fitness).*")) return "PRE_HIRE_CHECKS";
        if (s.matches(".*(interview|loop|panel|chat|shadow|role-play|tour).*")) return "INTERVIEW";
        if (s.matches(".*(assessment|test|exercise|project|programming|simulator|sim check|skills|case study"
                + "|demonstration|evaluation|checklist|presentation).*")) return "ASSESSMENT";
        if (s.matches(".*(screen|call).*")) return "SCREENING";
        if (s.matches(".*(application|resume|review|shortlist).*")) return "NEW_SUBMISSION";
        return "OTHER";
    }

    static String appliesTo(String rule) {
        String s = rule.toLowerCase();
        if (s.contains("requisition")) return "REQUISITION";
        if (s.matches(".*(offer|bonus|pay|compensation|equity|draw|guarantee|premium|differential|salary|sign-on|joining).*"))
            return "OFFER";
        if (s.matches(".*(hire|works council|certif|visa|union|disclosure|rehire).*")) return "CANDIDATE";
        return "OTHER";
    }

    /** "ALL" unless the item is a minority practice overall but universal in some countries (e.g. DE Works Council). */
    static List<String> countries(BlueprintItem i) {
        if ((double) i.support() / i.total() >= 0.5 || i.geoSupport() == null) return List.of("ALL");
        var full = i.geoSupport().stream().filter(g -> g.total() > 0 && g.support() == g.total()).map(GeoSupport::geography).toList();
        return full.isEmpty() ? List.of("ALL") : full;
    }

    static Map<String, Object> build(Blueprint bp) {
        var statuses = new ArrayList<Map<String, Object>>();
        var roles = new ArrayList<Map<String, Object>>();
        var chains = new ArrayList<Map<String, Object>>();
        var trace = new ArrayList<Map<String, Object>>();
        int seq = 0;
        for (BlueprintItem i : bp.items()) {
            String detail = i.status() == Status.EDITED ? i.editedDetail() : i.detail();
            String confidence = i.support() + "/" + i.total();
            switch (i.kind()) {
                case STAGE -> statuses.add(ordered("sequence", ++seq, "status", i.name(), "bin", bin(i.name()),
                        "appliesToCountries", countries(i), "confidence", confidence, "blueprintItemId", i.id()));
                case ROLE -> roles.add(ordered("role", i.name(), "description", detail,
                        "confidence", confidence, "blueprintItemId", i.id()));
                case APPROVAL_RULE -> chains.add(ordered("name", i.name(), "appliesTo", appliesTo(i.name() + " " + detail),
                        "approvers", i.approvers() == null ? List.of() : i.approvers(), "appliesToCountries", countries(i),
                        "description", detail, "confidence", confidence, "blueprintItemId", i.id()));
            }
            trace.add(ordered("blueprintItemId", i.id(), "evidence", i.evidence()));
        }
        return ordered(
                "_notice", NOTICE,
                "template", ordered("name", title(bp.industry()) + " – " + bp.workflowType() + " blueprint",
                        "industry", bp.industry(), "jobFamily", bp.workflowType(), "sourceImplementations", bp.sourceDocIds()),
                "recruitingWorkflow", ordered("statuses", statuses),
                "userRoles", roles,
                "approvalChains", chains,
                "traceability", trace);
    }

    private static String title(String s) {
        return s.isEmpty() ? s : Character.toUpperCase(s.charAt(0)) + s.substring(1);
    }

    private static Map<String, Object> ordered(Object... kv) {
        var m = new LinkedHashMap<String, Object>();
        for (int i = 0; i < kv.length; i += 2) m.put((String) kv[i], kv[i + 1]);
        return m;
    }
}
